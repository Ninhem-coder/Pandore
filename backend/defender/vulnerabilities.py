@handle_tool_errors
def get_expiring_certificates(within_days: int = 90) -> list[dict]:
    """
    "Expiring server certificates" du dashboard natif MDVM (tvm-dashboard-insights) :
    certificats serveur déjà expirés ou expirant dans les `within_days` prochains jours,
    détectés par Defender sur les devices (table DeviceTvmCertificateInfo).

    ATTENTION schéma vérifié le 2026-08-12 sur le tenant de production, PAS de mémoire :
    cette table n'a PAS de colonne `Timestamp` ni `DeviceName` (contrairement à la plupart
    des tables Advanced Hunting) — colonnes réelles : DeviceId, Thumbprint, Path,
    SerialNumber, IssuedTo (Object), IssuedBy (Object), FriendlyName, SignatureAlgorithm,
    KeySize, ExpirationDate, IssueDate, SubjectType, KeyUsage (Object), ExtendedKeyUsage
    (Object). Le nom de device est donc résolu via une jointure sur DeviceInfo, même
    principe que search_vulnerabilities. Table VIDE sur le tenant de production au moment
    de l'écriture (0 ligne) — la fonction est écrite pour être correcte le jour où des
    certificats y apparaîtront (déploiement de la fonctionnalité de découverte de certs
    MDE), pas seulement pour ce cas vide ; un tenant sans résultat n'est pas un bug.

    `IssuedTo`/`IssuedBy` sont des objets (ex. {"CN": "...", "O": "..."}) — on n'expose que
    le Common Name (`CN`) côté API, plus lisible qu'un objet brut pour le frontend.
    """
    safe_days = max(1, min(int(within_days), 3650))
    kql = f"""
DeviceTvmCertificateInfo
| where ExpirationDate < now() + {safe_days}d
| join kind=leftouter (
    DeviceInfo
    | summarize arg_max(Timestamp, DeviceName, MachineGroup) by DeviceId
  ) on DeviceId
| project DeviceId, DeviceName, MachineGroup, Thumbprint, FriendlyName, IssuedTo, IssuedBy, SubjectType, ExpirationDate, IssueDate
| order by ExpirationDate asc
| take 500
"""
    hunting = run_hunting_query(kql)
    if isinstance(hunting, dict) and hunting.get("error"):
        return [hunting]

    now = datetime.now(timezone.utc)
    results = []
    for r in hunting.get("results", []):
        expiration_raw = r.get("ExpirationDate")
        days_remaining = None
        bucket = "unknown"
        if expiration_raw:
            try:
                expiration = datetime.fromisoformat(str(expiration_raw).replace("Z", "+00:00"))
                days_remaining = (expiration - now).days
                if days_remaining < 0:
                    bucket = "expired"
                elif days_remaining <= 30:
                    bucket = "30"
                elif days_remaining <= 60:
                    bucket = "60"
                else:
                    bucket = "90"
            except ValueError:
                pass

        issued_to = r.get("IssuedTo")
        common_name = issued_to.get("CN") if isinstance(issued_to, dict) else issued_to

        results.append(
            {
                "device_id": r.get("DeviceId"),
                "device_name": r.get("DeviceName") or "Inconnu",
                "machine_group": r.get("MachineGroup"),
                "thumbprint": r.get("Thumbprint"),
                "friendly_name": r.get("FriendlyName") or common_name or "Certificat sans nom",
                "subject_type": r.get("SubjectType"),
                "expiration_date": expiration_raw,
                "days_remaining": days_remaining,
                "bucket": bucket,
            }
        )
    return results


@handle_tool_errors
def get_top_vulnerable_apps_by_exposure(level: str, top: int = 5) -> list[dict]:
    """
    Onglet "Secure Score" > "Par criticité" (2026-08-12) : pour un niveau d'exposition MDE
    donné (High/Medium/Low/None), les logiciels vulnérables les plus répandus parmi les
    devices de CE niveau, avec les chemins disque où chacun a été détecté (évidence
    DeviceTvmSoftwareEvidenceBeta, même table que search_vulnerabilities) ET la liste des
    devices concernés (noms, `DeviceInfo.DeviceName`) — ajoutée le 2026-08-12 (v2, demande de
    Nicolas) car une partie du parc (mobile/Linux) n'a AUCUNE évidence de chemin disque (table
    `DeviceTvmSoftwareEvidenceBeta` vide pour ces plateformes) : sans les noms de devices, ces
    lignes n'affichaient que "Aucun chemin d'évidence retrouvé" sans rien d'exploitable.

    Vérifié en conditions réelles sur le tenant de production le 2026-08-12, AVANT
    d'écrire cette fonction (level="High" : Microsoft Office 30 devices/100 CVE, OpenSSL
    29 devices/78 CVE, Chrome 25 devices/1734 CVE, FortiClient 23/21, Log4j 14/15 — avec
    chemins disque réels par logiciel, ex. C:\\Program Files\\Google\\Chrome\\Application\\
    chrome.exe). `mv-expand DiskPaths` avant le `make_set` : `DeviceTvmSoftwareEvidenceBeta.
    DiskPaths` est lui-même un tableau par ligne (device, logiciel) — sans l'expansion,
    make_set() agrégerait des tableaux de tableaux plutôt qu'un ensemble de chemins
    individuels. `DeviceNames` (v2) re-vérifié en direct avec `arg_max(Timestamp,
    ExposureLevel, DeviceName)` sur level="Low" : bixby_for_android (7 devices, noms Android
    complets), iphone_os (6 devices, noms iOS), ubuntu-advantage-tools_for_linux (3 devices
    Linux) — tous avec Paths=[] comme attendu, confirmant que DeviceNames est la bonne
    substitution pour ces cas.

    Le niveau d'exposition est résolu ici via `DeviceInfo.ExposureLevel` (Advanced Hunting,
    dédupliqué par `arg_max(Timestamp, ...)` comme dans get_expiring_certificates), PAS via
    `/api/machines.exposureLevel` (utilisé par get_defender_summary/_format_machine) :
    nécessaire pour joindre dans la MÊME requête KQL sur DeviceId, sans aller-retour
    supplémentaire vers l'API REST. Les deux sources reflètent le même champ Microsoft mais
    ne sont pas garanties rafraîchies à l'exacte même seconde — un léger écart de devices
    entre le camembert (get_defender_summary, REST) et ce détail (KQL) est possible et normal,
    pas un bug.
    """
    safe_level = _escape_kql_string(level)
    safe_top = max(1, min(int(top), 20))
    kql = f"""
DeviceInfo
| summarize arg_max(Timestamp, ExposureLevel, DeviceName) by DeviceId
| where ExposureLevel =~ "{safe_level}"
| join kind=inner (
    DeviceTvmSoftwareVulnerabilities
    | where isnotempty(CveId)
    | project DeviceId, SoftwareVendor, SoftwareName, CveId
  ) on DeviceId
| join kind=leftouter (
    DeviceTvmSoftwareEvidenceBeta
    | project DeviceId, SoftwareName, DiskPaths
  ) on DeviceId, SoftwareName
| mv-expand DiskPaths
| summarize DeviceCount=dcount(DeviceId), CveCount=dcount(CveId), Paths=make_set(DiskPaths, 20), DeviceNames=make_set(DeviceName, 20) by SoftwareVendor, SoftwareName
| top {safe_top} by DeviceCount desc
"""
    hunting = run_hunting_query(kql)
    if isinstance(hunting, dict) and hunting.get("error"):
        return [hunting]

    results = []
    for r in hunting.get("results", []):
        paths = r.get("Paths") or []
        if not isinstance(paths, list):
            paths = [paths]
        device_names = r.get("DeviceNames") or []
        if not isinstance(device_names, list):
            device_names = [device_names]
        results.append(
            {
                "software_vendor": r.get("SoftwareVendor"),
                "software_name": r.get("SoftwareName"),
                "device_count": r.get("DeviceCount"),
                "cve_count": r.get("CveCount"),
                "paths": sorted(p for p in paths if p),
                "device_names": sorted(d for d in device_names if d),
            }
        )
    return results


