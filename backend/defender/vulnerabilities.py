"""
Exposure score, recommandations et Vulnerability Management (TVM) — extrait de
`defender/tools.py` à la revue d'architecture du 2026-08-17 (voir l'en-tête de
`defender/machines.py` pour le contexte complet du découpage).

Dépend de `defender.hunting.run_hunting_query` pour toutes les fonctions basées sur
Advanced Hunting (search_vulnerabilities et suivantes) — voir `defender/hunting.py` pour
pourquoi ce petit module est resté séparé plutôt que fusionné ici.
"""
import re
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone

import httpx

from common.http_client import handle_tool_errors
from defender.client import client
from defender.hunting import run_hunting_query

_CVE_PATTERN = re.compile(r"^CVE-\d{4}-\d+$", re.IGNORECASE)
_SEVERITY_ORDER = {"Critical": 4, "High": 3, "Medium": 2, "Low": 1}


def _escape_kql_string(value: str) -> str:
    """
    Échappe une valeur destinée à un littéral KQL entre guillemets doubles (requête
    Advanced Hunting) : double les backslashes puis échappe les guillemets doubles.
    Nécessaire car `search_vulnerabilities` interpole une recherche saisie par
    l'utilisateur (CVE ou nom de logiciel) directement dans le corps de la requête KQL —
    sans cet échappement, une entrée contenant un guillemet pourrait sortir du littéral et
    injecter une clause KQL arbitraire (même famille de risque que `escape_odata_string`
    pour OData, mais un délimiteur/syntaxe différents).
    """
    return str(value).replace("\\", "\\\\").replace('"', '\\"')


def _exploitability_level(vuln: dict) -> str:
    """
    Réduit les indicateurs d'exploit de la fiche CVE Defender (`/api/vulnerabilities/{id}`)
    à une seule étiquette catégorielle, sévérité croissante — plus proche à lire dans un
    tableau qu'trois booléens séparés. `exploitInKit` (disponible dans un kit d'exploit
    "clé en main") est le signal le plus grave, avant un simple exploit public référencé.
    """
    if vuln.get("exploitInKit"):
        return "ExploitInKit"
    if vuln.get("exploitVerified"):
        return "ExploitVerified"
    if vuln.get("publicExploit"):
        return "PublicExploit"
    return "NoExploit"


def _fetch_vuln_metadata(cve: str) -> tuple[str | None, float | None, str, str | None, float | None, bool, bool]:
    """Sévérité/CVSS/exploitabilité/description/EPSS/signaux d'exploit côté catalogue TVM pour
    UNE CVE — appelée en parallèle (`ThreadPoolExecutor`) par `search_vulnerabilities` ET
    `get_top_vulnerabilities` (extraite au niveau module le 2026-09-01 pour ce 2e appelant,
    plutôt que dupliquée).

    `description` (2026-09-01, demande de Nicolas : "tu peux pas faire une recherche sur
    internet en fonction de la CVE cliquée ?") — inutile d'appeler un service tiers, le champ
    existe déjà dans CETTE MÊME réponse `/api/vulnerabilities/{cveId}`, déjà interrogée ici
    pour severity/cvssV3, juste jamais extrait avant ce jour. Vérifié en direct contre le
    tenant de production (CVE-2026-42767, CVE-2026-34182) : Microsoft fournit un texte structuré
    (Summary/Impact/Remediation/AdditionalInformation) se terminant par la mention "Generated by
    AI" — laissée telle quelle plutôt que masquée, c'est une information sur la provenance du
    texte que l'admin doit pouvoir voir, pas un artefact à nettoyer.

    `epss`/`exploit_in_wild`/`exploit_kit` (2026-09-02, bloc "Renseignement externe" de la popup
    de VulnerabilitiesTab.jsx) : MÊME réponse `/api/vulnerabilities/{cveId}` que ci-dessus,
    encore trois champs jamais extraits avant ce jour — `epss` (probabilité d'exploitation sous
    30 jours, score FIRST.org, fraction 0-1 chez Microsoft), `exploitVerified` (exploitation
    confirmée en conditions réelles) et `exploitInKit` (intégré à un kit d'exploit public,
    signal le plus grave — déjà utilisé par `_exploitability_level` ci-dessus, ici exposé tel
    quel EN PLUS du résumé catégoriel pour affichage en deux lignes distinctes côté UI).
    """
    try:
        vuln = client.get(f"/api/vulnerabilities/{cve}")
        return (
            vuln.get("severity"),
            vuln.get("cvssV3"),
            _exploitability_level(vuln),
            vuln.get("description"),
            vuln.get("epss"),
            bool(vuln.get("exploitVerified")),
            bool(vuln.get("exploitInKit")),
        )
    except httpx.HTTPError:
        # CVE trop récente ou hors catalogue TVM Microsoft (voir avertissement du skill
        # audit-vuln-defender) : on garde le résultat quand même plutôt que de perdre la
        # ligne. `httpx.HTTPError` (pas seulement `HTTPStatusError`) — un simple aléa
        # réseau/timeout sur UNE SEULE CVE parmi plusieurs en parallèle ne doit jamais faire
        # perdre les données déjà agrégées pour toutes les autres CVE de l'appel.
        return None, None, "NoExploit", None, None, False, False


